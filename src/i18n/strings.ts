const tables: Record<Lang, Record<StringKey, string>> = { ru, en };

let current: Lang = 'ru';

export function setLang(lang: Lang): void {
  current = lang;
  document.documentElement.lang = lang;
}

export function getLang(): Lang {
  return current;
}

export function detectLang(): Lang {
  const nav = typeof navigator !== 'undefined' ? navigator.language : 'ru';
  return nav.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

export function t(key: StringKey, vars?: Record<string, string | number>): string {
  let s = tables[current][key] ?? key;
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, String(vars[k]));
  return s;
}

/** Dynamic key lookup for data-driven content (e.g. upgrade ids). */
export function tk(key: string, vars?: Record<string, string | number>): string {
  return key in ru ? t(key as StringKey, vars) : key;
}
